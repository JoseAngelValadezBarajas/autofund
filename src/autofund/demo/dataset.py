"""The synthetic demo dataset the public Research Control Center is built from.

A clone of this repository has no `artifacts/` directory — that is private runtime state and is
gitignored. Without a dataset the Control Center would render an empty shell, which would make the
project look like it does nothing and would hide the actual architecture from a new reader. So Demo
mode generates a compact, deterministic fixture set that exercises every surface: the experiment
registry, the alpha registry, the evidence lineage, the campaigns and the eligibility matrix.

**Everything here is invented.** The fingerprints, intervals, observation counts and economics are
synthetic, and every generated document carries `SYNTHETIC_DEMO` provenance. What is *not* invented
is the shape: the documents are written at the same paths, with the same keys, that the real
certification scripts produce, so the registry reads them through exactly the code path it uses for
real evidence. A demo built on a demo-specific reader would prove nothing about the real one.

**The story is representative, not flattering.** The fixture describes the same scientific position
the real project reached: an information source that predicts, that cannot pay for itself at retail
friction, that is therefore not eligible for production, and whose current action is `NO_TRADE`.
Negative results are the project's strongest property and the demo shows one. It is not a
profitability claim and must never be edited into one.

**Generation is deterministic.** No timestamp comes from the clock and nothing depends on
filesystem iteration order, so two generations produce byte-identical files and therefore the same
registry digest. That is asserted by test, because a demo whose output drifts cannot verify a read
model.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from autofund.research.registry import ExperimentSeed

DEMO_DATASET_VERSION = "autofund.demo-dataset.v1"

#: Label applied to every generated document so nothing can mistake it for real evidence.
PROVENANCE = "SYNTHETIC_DEMO"

#: Fixed instant so generation never reads the clock. Deliberately in the past and obviously
#: synthetic rather than a plausible recent date.
GENERATED_AT = "2026-01-01T00:00:00Z"

DEMO_EXPERIMENT_ID = "demo-0-1"
DEMO_ALPHA_ID = "DEMO_CROSS_MARKET_SIGNAL_V1"

#: The paths the registry reads. These are the real milestone paths, not demo-specific ones, so
#: the demo exercises the production read path rather than a parallel one.
#:
#: The experiment document sits in the same directory as the capture it describes, because the
#: registry locates a seed's capture relative to its own artifact. Keeping them together means the
#: demo needs no special case in the registry at all.
EXPERIMENT_ARTIFACT = "mvp/cross-venue/mvp-demo-0-1-certification.json"
#: The alpha document is written at the path the alpha reader already consults, so the demo
#: exercises the production read path rather than a parallel one. In a demo artifacts root that
#: path holds synthetic content; the root is separate, so no real evidence can be overwritten.
ALPHA_ARTIFACT = "mvp/alpha/mvp-0-2-6-certification.json"
CROSS_VENUE_CAPTURE = "mvp/cross-venue/capture"

_DEMO_NOTICE = (
    "Synthetic demonstration data generated by AutoFund demo mode. It is not a backtest, not "
    "historical performance, and not evidence about any live account. It exists only to "
    "demonstrate the research workflow and the Research Control Center.")

#: The experiment the demo declares. Supplied to the registry by the caller rather than inserted
#: into the registry's own seed list, so production never learns that demo mode exists.
DEMO_SEED = ExperimentSeed(
    experiment_id=DEMO_EXPERIMENT_ID,
    milestone="DEMO 0.1",
    title="Cross-market relationship, from hypothesis to refusal",
    hypothesis=(
        "A lagging relationship between two MXN pairs predicts short-horizon direction well "
        "enough to pay for a round trip at retail friction"),
    artifact=EXPERIMENT_ARTIFACT,
    markets=("BTC/MXN", "ETH/MXN"),
    strategies=(),
    alpha=(DEMO_ALPHA_ID,),
)


@dataclass(frozen=True, slots=True)
class DemoPaths:
    """Where each generated document lands, relative to the artifacts root."""

    root: Path

    @property
    def experiment(self) -> Path:
        return self.root / EXPERIMENT_ARTIFACT

    @property
    def alpha(self) -> Path:
        return self.root / ALPHA_ARTIFACT

    @property
    def capture(self) -> Path:
        return self.root / CROSS_VENUE_CAPTURE

    def documents(self) -> tuple[Path, ...]:
        return (self.experiment, self.alpha)


def _write(path: Path, payload: dict[str, Any]) -> None:
    """Write one document deterministically: sorted keys, LF, trailing newline, no clock."""
    path.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    path.write_text(text, encoding="utf-8", newline="\n")


def _experiment() -> dict[str, Any]:
    """The experiment record, in the shape the registry's experiment reader consumes.

    The windows are declarations rather than measurements: they record what was searched and over
    what period, so the Control Center can show a predeclared protocol instead of a retrospective
    one.
    """
    return {
        "schema_version": DEMO_DATASET_VERSION,
        "provenance": PROVENANCE,
        "synthetic": True,
        "demo_notice": _DEMO_NOTICE,
        "status": "PREDICTIVE_NOT_ECONOMIC",
        "certified_at": GENERATED_AT,
        "baseline_commit": "demo0000",
        "development_window": {"hours": 720, "end": "2025-11-01T00:00:00Z"},
        "holdout_window": {"hours": 720, "end": "2025-12-01T00:00:00Z"},
        "forward_window": None,
        # The capture this experiment commissioned. Its collector ran correctly and still produced
        # no usable conclusion, because coverage is a property of the data rather than of the
        # process: health and conclusion are two different questions.
        "capture": {
            "coverage": {
                "required_hours": "72",
                "covered_hours": "6.5",
                "sufficient": False,
            },
        },
        "production_post_count": 0,
        "reason_codes": [
            "Synthetic demonstration: the relationship predicts direction but the measured "
            "movement is smaller than round-trip friction, so it is not economically usable",
            "development and holdout are synthetic windows, not measurements of real markets",
        ],
        "safety": {"production_post_count": 0, "exchange_mutations": 0},
    }


def _alpha() -> dict[str, Any]:
    """The alpha source: predictive, and not economic.

    This pairing is the thing the whole product exists to keep separate. A source that predicts a
    direction and a source that can pay for trading it are different findings, and the numbers here
    are chosen so the gap is unambiguous rather than marginal.
    """
    return {
        "schema_version": DEMO_DATASET_VERSION,
        "provenance": PROVENANCE,
        "synthetic": True,
        "demo_notice": _DEMO_NOTICE,
        "status": "PREDICTIVE_NOT_ECONOMIC",
        "certified_at": GENERATED_AT,
        "production_post_count": 0,
        "candidate": {
            "leader": "BTC/MXN",
            "follower": "ETH/MXN",
            "horizon_minutes": 5,
            "synthetic": True,
        },
        "validation": {"passed": True, "synthetic": True},
        "economic_translation": {
            "largest_bucket_mean_movement_bps": "3.140000000000000000000000000",
            "friction_bps": "172.0000000000000000000000000",
            "headroom_bps": "-168.8600000000000000000000000",
            "tradeable": False,
            "synthetic": True,
        },
        "frozen_alpha": {
            "fingerprint": "0" * 64,
            "label": "SYNTHETIC_DEMO_ALPHA",
            "synthetic": True,
        },
        "reason_codes": [
            "PREDICTIVE_BUT_MOVEMENT_BELOW_ROUND_TRIP_FRICTION",
            "SYNTHETIC_DEMO_FIXTURE",
        ],
        "safety": {"production_post_count": 0, "exchange_mutations": 0},
    }


def _capture_rows(*, book: str, reference: str) -> list[dict[str, Any]]:
    """A handful of records so the index shows it reads a JSONL stream by size and fingerprint.

    Kept tiny on purpose. Shipping a large capture to prove the indexer handles large captures
    would be exactly the accidental large-file publication this milestone exists to prevent.
    """
    return [
        {
            "seq": index,
            "provenance": PROVENANCE,
            "synthetic": True,
            "book": book,
            "reference_book": reference,
            "observed_at": f"2026-01-01T00:0{index}:00Z",
            "mid_dislocation_bps": "1.10",
            "reference_spread_bps": "8.40",
            "usable": True,
        }
        for index in range(4)
    ]


def generate(*, artifacts_root: Path) -> DemoPaths:
    """Write the whole demo dataset, deterministically and idempotently.

    Rewriting identical bytes on every run is intentional: it removes the need for a `--reset` and
    keeps a repeat build from changing the registry digest, which is what makes the digest usable
    as a verification signal at all.
    """
    root = artifacts_root.resolve(strict=False)
    root.mkdir(parents=True, exist_ok=True)
    paths = DemoPaths(root=root)

    _write(paths.experiment, _experiment())
    _write(paths.alpha, _alpha())

    capture = paths.capture
    capture.mkdir(parents=True, exist_ok=True)
    for book, reference in (("btc_mxn", "eth_mxn"), ("eth_mxn", "btc_mxn")):
        lines = "".join(
            json.dumps(row, sort_keys=True) + "\n"
            for row in _capture_rows(book=book, reference=reference))
        (capture / f"{book}.00000.jsonl").write_text(lines, encoding="utf-8", newline="\n")
    return paths


def is_demo_dataset(*, artifacts_root: Path) -> bool:
    """True when this root holds the synthetic dataset rather than real evidence.

    Checks the provenance field rather than the directory name, so a real artifact copied into a
    demo directory is not mislabelled and a demo artifact placed elsewhere is still recognised.
    """
    for document in DemoPaths(artifacts_root.resolve(strict=False)).documents():
        try:
            payload = json.loads(document.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        if isinstance(payload, dict) and payload.get("provenance") == PROVENANCE:
            return True
    return False
